"""Modular Compagnon 2: the enamel plates' letters, a bold condensed serif (DejaVu Serif Condensed Bold, assets/fonts/
serif, the Bitstream Vera licence) in two sizes, 16 levels of ink (4 bits a pixel, two to a byte, high nibble first).
Characters 32 .. 95 (capitals, figures, punctuation).
  gen_serif.py OUT.h"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

TTF = Path(__file__).resolve().parent.parent / "assets" / "fonts" / "serif" / "DejaVuSerifCondensed-Bold.ttf"
SIZES = {"BIG": 21, "SMALL": 13}


def build(px):
    f = ImageFont.truetype(str(TTF), px)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, data = [], bytearray()
    for c in range(32, 96):
        ch = chr(c)
        adv = round(f.getlength(ch))
        w = max(1, adv + 1)
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        px4 = [v * 15 // 255 for v in im.tobytes()]
        if len(px4) & 1:
            px4.append(0)
        off = len(data)
        data += bytes((px4[k] << 4) | px4[k + 1] for k in range(0, len(px4), 2))
        glyphs.append((off, w, adv))
    return h, asc, glyphs, data


def main(out):
    txt = ["/* generated by tools/gen_serif.py (DejaVu Serif Condensed Bold) */",
           "typedef struct { uint16_t off; uint8_t w, adv; } sf_glyph_t;",
           "typedef struct { uint8_t h, asc; const sf_glyph_t *g; const uint8_t *d; } sf_font_t;"]
    for name, px in SIZES.items():
        h, asc, g, d = build(px)
        txt.append(f"static const sf_glyph_t SF_{name}_G[64] = {{" + ", ".join(f"{{{o}, {w}, {a}}}" for o, w, a in g) + "};")
        rows = [", ".join(f"0x{b:02x}" for b in d[k:k + 24]) for k in range(0, len(d), 24)]
        txt.append(f"static const uint8_t SF_{name}_D[{len(d)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
        txt.append(f"static const sf_font_t SF_{name} = {{{h}, {asc}, SF_{name}_G, SF_{name}_D}};")
        print(f"serif {name}: {px} px, height {h}, {len(d)} B")
    Path(out).write_text("\n".join(txt) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
