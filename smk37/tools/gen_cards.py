"""Modular Compagnon 2: the town's postcards (assets/cards, captured from Modular Town V3.2's own interface) to a C
header. Each place by day at 240 x 150 and by night at 120 x 75 (the screen doubles it), 64 colours each (palette in
RGB565), LZSS-compressed (m1_draw.c mc_lz: a flag byte for 8 items, LSB first; a set bit is a match of 2 bytes,
12-bit distance back and 4-bit length - 3, a clear bit a literal byte; window 4096).
  gen_cards.py OUT.h"""
import sys, collections
from pathlib import Path
from PIL import Image, ImageEnhance

SRC = Path(__file__).resolve().parent.parent / "assets" / "cards"
CARDS = ["depart", "cook", "engineer", "postman", "painter", "vinyl", "lineman", "neon", "studio", "kiosk"]
DW, DH, NW, NH, NC = 240, 150, 120, 75, 64


def lzss(data):
    out, i, n = bytearray(), 0, len(data)
    table = collections.defaultdict(list)
    while i < n:
        fp = len(out); out.append(0); flags = 0
        for b in range(8):
            if i >= n:
                break
            best = bo = 0
            key = bytes(data[i:i + 3])
            if len(key) == 3:
                for j in reversed(table[key][-96:]):
                    if i - j > 4095:
                        break
                    l = 3
                    while l < 18 and i + l < n and data[j + l] == data[i + l]:
                        l += 1
                    if l > best:
                        best, bo = l, i - j
                        if l == 18:
                            break
            if best >= 3:
                flags |= 1 << b
                out += bytes([bo >> 4, ((bo & 15) << 4) | (best - 3)])
                for k in range(best):
                    kk = bytes(data[i + k:i + k + 3])
                    if len(kk) == 3:
                        table[kk].append(i + k)
                i += best
            else:
                out.append(data[i])
                if len(key) == 3:
                    table[key].append(i)
                i += 1
        out[fp] = flags
    return out


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def card(path, w, h, lift):
    im = Image.open(path).convert("RGB").resize((w, h), Image.LANCZOS)
    if lift:                                     # the night, a little lighter: the panel is small
        im = ImageEnhance.Brightness(im).enhance(1.35)
        im = ImageEnhance.Contrast(im).enhance(1.08)
    q = im.quantize(colors=NC, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:NC * 3]
    pal += [0] * (NC * 3 - len(pal))
    return [rgb565(*pal[k * 3:k * 3 + 3]) for k in range(NC)], lzss(q.tobytes())


def arr(name, data, per=24):
    rows = [", ".join(f"0x{b:02x}" for b in data[k:k + per]) for k in range(0, len(data), per)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main(out):
    day, night, dpal, npal, doff, noff = bytearray(), bytearray(), [], [], [0], [0]
    for c in CARDS:
        p, d = card(SRC / f"{c}_jour.png", DW, DH, False)
        dpal.append(p); day += d; doff.append(len(day))
        p, d = card(SRC / f"{c}_nuit.png", NW, NH, True)
        npal.append(p); night += d; noff.append(len(night))
    pal = lambda P: "{\n" + ",\n".join("    {" + ", ".join(f"0x{v:04x}" for v in row) + "}" for row in P) + "\n}"
    txt = ["/* generated by tools/gen_cards.py from assets/cards (Modular Town V3.2's own pictures) */",
           f"#define MC_NCARD {len(CARDS)}u", f"#define MC_CW {DW}u", f"#define MC_CH {DH}u",
           f"#define MC_NW {NW}u", f"#define MC_NH {NH}u",
           "enum { " + ", ".join(f"MC_CARD_{c.upper()}" for c in CARDS) + " };",
           f"static const uint16_t MC_DPAL[MC_NCARD][{NC}] = {pal(dpal)};",
           f"static const uint16_t MC_NPAL[MC_NCARD][{NC}] = {pal(npal)};",
           f"static const uint32_t MC_DOFF[MC_NCARD + 1] = {{{', '.join(map(str, doff))}}};",
           f"static const uint32_t MC_NOFF[MC_NCARD + 1] = {{{', '.join(map(str, noff))}}};",
           arr("MC_DDATA", day), arr("MC_NDATA", night)]
    Path(out).write_text("\n".join(txt))
    print(f"cards: {len(CARDS)} places, day {len(day)} B, night {len(night)} B")


if __name__ == "__main__":
    main(sys.argv[1])
